def _draw_five_column_table(
    c: canvas.Canvas,
    *,
    title: str,
    rows: list[dict],
    columns: list[dict],
    width: float,
    height: float,
    empty_message: str,
) -> None:
    section_title_y = height - 135
    table_x = 30
    table_w = width - 60
    header_h = 32
    row_h = 24
    first_page_top = section_title_y - 16
    next_page_top = height - 170

    col_widths = [150, 150, 62, 68, 85]

    def _draw_section_header(y_top: float) -> float:
        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 12)
        c.drawString(table_x, y_top, title)

        table_top = y_top - 14
        c.setFillColor(colors.whitesmoke)
        c.setStrokeColor(colors.lightgrey)
        c.rect(table_x, table_top - header_h, table_w, header_h, stroke=1, fill=1)

        c.setFillColor(colors.black)
        c.setFont("Helvetica-Bold", 8)
        x_cursor = table_x
        for index, column in enumerate(columns):
            text_x = x_cursor + 6
            c.drawString(text_x, table_top - 20, column["label"])
            x_cursor += col_widths[index]
            if index < len(columns) - 1:
                c.line(x_cursor, table_top, x_cursor, table_top - header_h)

        return table_top - header_h

    current_bottom = _draw_section_header(first_page_top)

    if not rows:
        c.setStrokeColor(colors.lightgrey)
        c.setFillColor(colors.white)
        c.rect(table_x, current_bottom - row_h, table_w, row_h, stroke=1, fill=1)
        c.setFillColor(colors.black)
        c.setFont("Helvetica", 9)
        c.drawString(table_x + 10, current_bottom - 16, empty_message)
        return

    for index, row in enumerate(rows):
        next_row_bottom = current_bottom - row_h
        if next_row_bottom < TABLE_BOTTOM_MARGIN:
            c.showPage()
            current_bottom = _draw_section_header(next_page_top)
            next_row_bottom = current_bottom - row_h

        c.setFillColor(colors.white if index % 2 == 0 else colors.HexColor("#f8fafc"))
        c.setStrokeColor(colors.lightgrey)
        c.rect(table_x, current_bottom - row_h, table_w, row_h, stroke=1, fill=1)

        x_cursor = table_x
        for i in range(len(columns) - 1):
            x_cursor += col_widths[i]
            c.line(x_cursor, current_bottom, x_cursor, current_bottom - row_h)

        c.setFillColor(colors.black)
        c.setFont("Helvetica", 8)
        x_cursor = table_x
        for i, column in enumerate(columns):
            raw_value = row.get(column["key"], "")
            value = column["formatter"](raw_value)
            text = _trim_text(c, value, col_widths[i] - 10, "Helvetica", 8)
            c.drawString(x_cursor + 5, current_bottom - 16, text)
            x_cursor += col_widths[i]

        current_bottom = next_row_bottom


